// Playwright CLI run-code script. Requires a disposable source folder already
// filled into #folder, a sibling "destination", and the documented review files.
async page => {
  const source = await page.locator('#folder').inputValue();
  if (!source.includes('smart-review-')) throw new Error('Use the disposable smart-review fixture, never real Downloads');
  const destination = source.replace(/source$/, 'destination');
  await page.locator('#folder').fill('');
  await page.screenshot({path:'.runtime/smart-dashboard.png',fullPage:true});
  const categories = page.locator('#settings > details').nth(0);
  await categories.locator(':scope > summary').click();
  await categories.getByPlaceholder('Studies/Distributed Systems',{exact:true}).fill('Studies/AI');
  await categories.getByRole('button',{name:'Create category',exact:true}).click();
  const rules = page.locator('#settings > details').nth(1);
  await rules.locator(':scope > summary').click();
  await rules.getByLabel('Rule ID',{exact:true}).fill('robot-notes');
  await rules.locator('select[name=category]').selectOption('Studies/AI');
  await rules.getByLabel('Keywords (comma separated)',{exact:true}).fill('robot');
  await rules.getByLabel('Extensions (optional)',{exact:true}).fill('pdf, pptx');
  await rules.getByRole('button',{name:'Save rule',exact:true}).click();
  await page.locator('#folder').fill(source);
  await page.getByRole('button',{name:'Scan & Preview',exact:true}).click();
  const row = name => page.locator('.file-row').filter({has:page.getByText(name,{exact:true})});
  if (await row('Computer Networks lecture.pdf').locator('select').inputValue() !== 'Studies/Computer Networks') throw new Error('Subject classification failed');
  if (await row('robot.pdf').locator('select').inputValue() !== 'Studies/AI') throw new Error('Custom rule failed');
  if (await row('mystery839.pdf').locator('input[type=checkbox]').isChecked()) throw new Error('Uncertain file selected silently');
  if (!(await row('pending.pdf.crdownload').innerText()).includes('Incomplete download')) throw new Error('Incomplete file not skipped');
  if (!(await page.getByRole('button',{name:'Apply these moves',exact:true}).isDisabled())) throw new Error('Apply allowed before destination');
  await page.getByRole('radio',{name:'A separate local folder',exact:false}).check();
  await page.getByLabel('Separate destination path',{exact:true}).fill(destination);
  await page.getByRole('button',{name:'Set destination',exact:true}).click();
  if (!(await row('invoice.txt').innerText()).includes('Conflict: skipped')) throw new Error('Collision not shown');
  await page.locator('#search').fill('DBMS');
  if (await page.locator('.file-row:visible').count() !== 1) throw new Error('Search should match only the DBMS file');
  await page.locator('#search').fill('');
  await page.locator('#sort').selectOption('category');
  await page.getByRole('button',{name:'Deselect visible',exact:true}).click();
  await row('Computer Networks lecture.pdf').locator('input[type=checkbox]').check();
  await row('DBMS assignment.pptx').locator('input[type=checkbox]').check();
  await page.locator('select[name=bulk_category]').selectOption('Projects');
  await page.getByRole('button',{name:'Update selected categories',exact:true}).click();
  if (await row('DBMS assignment.pptx').locator('select').inputValue() !== 'Projects') throw new Error('Bulk edit failed');
  await page.getByRole('button',{name:'Select visible',exact:true}).click();
  await row('setup.exe').locator('input[type=checkbox]').uncheck();
  await row('mystery839.pdf').locator('select').selectOption('Personal');
  await page.getByRole('button',{name:'Save preview edits',exact:true}).click();
  await page.getByLabel('I reviewed the exact paths and approve moving the selected files.',{exact:true}).check();
  await page.getByRole('button',{name:'Apply these moves',exact:true}).click();
  if (!(await page.locator('.notice').innerText()).includes('Moved 5 of 6 files')) throw new Error('Unexpected apply result');
  await page.locator('#history .operation').first().locator(':scope > summary').click();
  const robot = page.locator('#history tr').filter({has:page.getByText('robot.pdf',{exact:true})});
  await robot.getByRole('button',{name:'Undo file',exact:true}).click();
  if (!(await page.locator('.restore').innerText()).includes('robot.pdf')) throw new Error('Individual restore preview missing');
  await page.getByLabel('I approve restoring the eligible files shown above.',{exact:true}).check();
  await page.getByRole('button',{name:'Confirm restore',exact:true}).click();
  if (!(await page.locator('.notice').innerText()).includes('restored 1 of 1')) throw new Error('Individual undo failed');
  await page.getByRole('button',{name:'Undo Last Organization',exact:true}).click();
  await page.getByLabel('I approve restoring the eligible files shown above.',{exact:true}).check();
  await page.getByRole('button',{name:'Confirm restore',exact:true}).click();
  if (!(await page.locator('.notice').innerText()).includes('restored 4 of 4')) throw new Error('Batch undo failed');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.runtime/smart-mobile.png',fullPage:true});
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile page overflow');
  return 'PASS: settings, custom rule, scan, explicit destination, search/sort/select, bulk edit, apply, collision, individual undo, batch undo, mobile';
}
